/**
 * fsn.php — กฎการกำหนดหมายเลขพัสดุตามระบบ FSN (Federal Stock Number)
 *
 * อ้างอิง: คู่มือการกำหนดหมายเลขพัสดุ
 *          สำนักพัฒนาระบบงานและบุคลากร สำนักงบประมาณ (มกราคม 2543)
 *
 * รูปแบบ: 11 หลัก แบ่งเป็น 3 ชุด  GGCC-TTT-DDDD
 *
 *   GG   (2 หลัก)  กลุ่ม (Group)        10-99
 *   CC   (2 หลัก)  ประเภท (Class)       ประเภทของพัสดุภายในกลุ่มนั้น
 *   TTT  (3 หลัก)  ชนิด (Type)          ชนิดของพัสดุในกลุ่มและประเภทนั้น
 *   DDDD (4 หลัก)  รายละเอียด           0001-9999 เลขลำดับคุณลักษณะ
 *
 * ตัวอย่างจากคู่มือ: 7110-002-0001 = ตู้เก็บเอกสาร 4 ลิ้นชัก
 *   71 = กลุ่มเครื่องตกแต่ง, 10 = ประเภทเครื่องตกแต่งสำนักงาน,
 *   002 = ตู้เก็บเอกสารที่เป็นลิ้นชัก, 0001 = คุณลักษณะแรกของชนิดนี้
 *
 * กฎสำคัญ 2 ข้อจากคู่มือ:
 *   1. ตัวเลข 4 หลักแรกกำหนดเหมือนกันทุกหน่วยงาน (มาจากคู่มือ)
 *   2. ตัวเลข 4 หลักสุดท้ายแต่ละหน่วยงานกำหนดเอง เรียงลำดับไม่ซ้ำกัน
 *      และ "เมื่อคุณลักษณะของพัสดุเปลี่ยนไป ตัวเลขชุดนี้ก็จะเปลี่ยนไป"
 */

if (!defined('FSN_PATTERN')) {
    /** รูปแบบที่ใช้ตรวจสอบ: 4 หลัก - 3 หลัก - 4 หลัก */
    define('FSN_PATTERN', '/^(\d{2})(\d{2})-(\d{3})-(\d{4})$/');
    /** ใช้กับ attribute pattern ของ <input> (ไม่มีเครื่องหมาย / ครอบ) */
    define('FSN_HTML_PATTERN', '[0-9]{4}-[0-9]{3}-[0-9]{4}');
}

if (!function_exists('fsn_parse')) {

    /**
     * แยกหมายเลขพัสดุออกเป็น 4 ส่วน คืนค่า null ถ้ารูปแบบไม่ถูกต้อง
     * @return array{group:string,class:string,type:string,serial:string,prefix:string}|null
     */
    function fsn_parse(string $code): ?array {
        $code = trim($code);
        if (!preg_match(FSN_PATTERN, $code, $m)) {
            return null;
        }
        // กลุ่มต้องอยู่ในช่วง 10-99 ตามคู่มือ (แบ่งพัสดุเป็น 76 กลุ่ม เริ่มจากกลุ่มที่ 10)
        if ((int)$m[1] < 10) {
            return null;
        }
        // ชุดที่ 3 เริ่มจาก 0001 — 0000 ไม่ใช่เลขลำดับที่ถูกต้อง
        if ($m[4] === '0000') {
            return null;
        }
        return [
            'group'  => $m[1],
            'class'  => $m[1] . $m[2],   // ประเภท = 4 หลักแรกทั้งชุด
            'type'   => $m[3],
            'serial' => $m[4],
            'prefix' => $m[1] . $m[2] . '-' . $m[3],
        ];
    }

    /** ตรวจว่าหมายเลขถูกต้องตามระบบ FSN หรือไม่ */
    function fsn_is_valid(string $code): bool {
        return fsn_parse($code) !== null;
    }

    /**
     * ประกอบหมายเลขจากส่วนย่อย
     * @param string $class  ประเภท 4 หลัก เช่น '7110'
     * @param string $type   ชนิด 3 หลัก เช่น '002'
     * @param int    $serial เลขลำดับ 1-9999
     */
    function fsn_format(string $class, string $type, int $serial): string {
        return sprintf('%04d-%03d-%04d', (int)$class, (int)$type, $serial);
    }

    /**
     * หาเลขลำดับ (ชุดที่ 3) ตัวถัดไปที่ยังว่างของ prefix หนึ่ง ๆ
     *
     * คู่มือระบุว่าเลขชุดนี้ "เรียงเป็นหมายเลขลำดับของคุณลักษณะของพัสดุ
     * ซึ่งตัวเลขจะไม่ซ้ำกัน เริ่มจาก 0001 ถึง 9999"
     *
     * @param string $prefix เช่น '7110-002'
     * @return int เลขลำดับถัดไป หรือ 0 ถ้าเต็ม 9999 แล้ว
     */
    function fsn_next_serial(PDO $conn, string $prefix): int {
        if (!preg_match('/^\d{4}-\d{3}$/', $prefix)) {
            return 0;
        }
        $stmt = $conn->prepare(
            "SELECT asset_code FROM assets
             WHERE asset_code LIKE ?
             ORDER BY asset_code DESC"
        );
        $stmt->execute([$prefix . '-%']);

        $max = 0;
        foreach ($stmt->fetchAll(PDO::FETCH_COLUMN) as $code) {
            $p = fsn_parse((string)$code);
            // นับเฉพาะรหัสที่ถูกรูปแบบและอยู่ใน prefix เดียวกันจริง ๆ
            if ($p && $p['prefix'] === $prefix) {
                $max = max($max, (int)$p['serial']);
            }
        }
        return $max >= 9999 ? 0 : $max + 1;
    }

